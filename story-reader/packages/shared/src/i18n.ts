export const defaultReaderSettings: ReaderSettings = {
  fontSize: 'md',
  theme: 'light',
  background: 'default',
  lineHeight: 'relaxed',
  fontFamily: 'sans',
  language: 'vi',
};

const validFontSizes = ['sm', 'md', 'lg', 'xl'] as const;
const validLineHeights = ['normal', 'relaxed', 'loose'] as const;
const validFontFamilies = ['sans', 'serif'] as const;

export function normalizeReaderSettings(settings?: Partial<ReaderSettings> | null): ReaderSettings {
  const value = settings ?? {};
  return {
    fontSize: validFontSizes.includes(value.fontSize as ReaderSettings['fontSize'])
      ? value.fontSize as ReaderSettings['fontSize']
      : defaultReaderSettings.fontSize,
    theme: readerThemes.some((theme) => theme.value === value.theme)
      ? value.theme as ReaderTheme
      : defaultReaderSettings.theme,
    background: ['default', 'sepia', 'black'].includes(value.background as any)
      ? (value.background as any)
      : defaultReaderSettings.background,
    lineHeight: validLineHeights.includes(value.lineHeight as ReaderSettings['lineHeight'])
      ? value.lineHeight as ReaderSettings['lineHeight']
      : defaultReaderSettings.lineHeight,
    fontFamily: validFontFamilies.includes(value.fontFamily as ReaderSettings['fontFamily'])
      ? value.fontFamily as ReaderSettings['fontFamily']
      : defaultReaderSettings.fontFamily,
    language: languages.some((language) => language.value === value.language)
      ? value.language as Language
      : defaultReaderSettings.language,
  };
}
